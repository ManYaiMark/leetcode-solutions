class Solution:
    """
    โจทย์: กำหนดจำนวนเต็ม n ให้นำตัวเลขที่ไม่ใช่ 0 มาต่อกันตามลำดับเดิมเพื่อสร้างจำนวน x 
    จากนั้นหาผลรวมของตัวเลขทั้งหมดใน x และคืนค่า x × ผลรวม หากไม่มีตัวเลขที่ไม่ใช่ 0 ให้ x = 0

    วิธีคิด
    ตามโจทย์คือถ้าเป็น 0 ก็จะเท่ากับ 0 เลยทำการ return 0
    หลังจากนั้น ประกาศตัวแปลสำหรับเก็บ sum , x 
    แล้วใช้ for loop ในการเช็คทีละต่ำแหน่ง 
    ข้อนี้หลักสูงสุดแค่ 9 หลักเลยไม่เยอะมาก
    """
    def sumAndMultiply(self, n: int) -> int:
        if n == 0 :
            return 0
        r = 0
        m = ''
        for i in str(n):
            if i == '0' :
                continue
            r += int(i)
            m = m + i
        return r * int(m)