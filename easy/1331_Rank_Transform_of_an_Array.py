class Solution:
    """
    โจทย์: กำหนดอาร์เรย์ nums ให้หาผลรวมสะสมในแต่ละตำแหน่ง 
    โดยตำแหน่ง i จะมีค่าเท่ากับผลรวมของสมาชิกตั้งแต่ตำแหน่ง 0 ถึง i แล้วคืนค่าอาร์เรย์ผลรวมสะสม

    วิธีคิด
    ตอนแรกนั่งคิดอยู่นานมากว่าจะทำยังไง ทำไปทำมาก็ไม่ได้
    เพราะคิดสลับกันไปหน่อย จนได้การคิดการใช้ dict ขึ้นมา
    1.sort set เพื่อหาค่าไม่ซ้ำแล้วก็เรียง
    2.สร้าง dict เก็บค่าตัวเลยแล้วก็ rank
    3.return list ที่นำค่า key ไปเก็บไว้ก่อนหน้านี้เพื่อนำมาเรียงในรูปแบบ arr เดิม
    """
    def arrayRankTransform(self, arr: list[int]) -> list[int]:
        s = sorted(set(arr))
        arr2 = dict()
        for i in range(len(s)):
            arr2[s[i]] = i+1     
        return [arr2[j] for j in arr]