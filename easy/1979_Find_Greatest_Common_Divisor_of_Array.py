class Solution:
    """
    โจทย์: กำหนดอาร์เรย์จำนวนเต็ม nums ให้หาค่าที่น้อยที่สุดและมากที่สุดในอาร์เรย์ 
    จากนั้นคืนค่า ห.ร.ม. (GCD) ของตัวเลขทั้งสอง

    วิธีคิด
    เนื่องจากเป็นข้อง่ายเลยทำการเขียนเพื่อหา min , max เองเพื่อให้มันไม่ง่ายเกินไป
    ส่วนหา ห.ร.ม. ใช้ฟังขั่นเขียนเอา จะง่ายต่อการเขียน และอ่าน
    """
    def findGCD(self, nums: list[int]) -> int:
        def gcd(a,b):
            # ถ้า b = 0 จะเป็นเท็จ
            while b :
                # หารเรื่อบๆจนกว่า b จะเป็น 0 
                a,b = b,a % b
            # ถ้า b เป็น 0 แล้วค่อยทำการ return a ที่เป็นตัวก่อนหน้า
            return a
        # กำหนดให้เยอะกว่าโจทย์เพื่อไม่ให้มันน้อยกว่าโจทย์
        minn = 1001 
        # กำหนดให้น้อยกว่าโจทย์เพื่อไม่ให้มันมากกว่าโจทย์
        maxn = 0
        # หาเลขมากสุดและน้อยสุด
        for i in nums:
            if i > maxn :
                maxn = i
            if i < minn :
                minn = i
        return gcd(minn,maxn)