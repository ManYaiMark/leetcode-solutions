class Solution:
    """
    โจทย์: กำหนดจำนวนเต็มบวก n ให้เลือกตัวเลข 2 หลักจาก n ที่ทำให้ผลคูณมีค่ามากที่สุด 
    แล้วคืนค่าผลคูณนั้น โดยสามารถเลือกเลขค่าเดียวกันได้หากปรากฏมากกว่า 1 ครั้ง

    แนวคิด
    หาค่าที่เยอะที่สุด 2 ตัว เลยใช้การ for loop เทียบทีละตัว
    """
    def maxProduct(self, n: int) -> int:
        L = -1
        R = -1
        for i in str(n) :
            i = int(i)
            if i > L :
                R = L
                L = i
            elif i > R :
                R = i
        return L * R

