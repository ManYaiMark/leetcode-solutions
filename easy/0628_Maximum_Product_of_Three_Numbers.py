class Solution:
    """
    โจทย์: กำหนดอาร์เรย์จำนวนเต็ม nums ให้เลือกตัวเลข 3 ตัว จากอาร์เรย์ โดยทำให้ผลคูณของทั้ง 3 ตัวมีค่ามากที่สุด แล้วคืนค่าผลคูณนั้น

    วิธีคิด หาวิธีที่จะได้มากที่สุด
    1. 3 ตัวหลังเป็นตัวมากสุด  (+) * (+) * (+) = (+)
    2. ตัวเป็นลบ - คูณกันแล้วได้เยอะกว่าแบบที่ 1  (-) * (-) * (+) = (+)
    แล้วนำมาหา max
    """
    def maximumProduct(self, nums: list[int]) -> int:
        nums.sort()
        a = nums[0] * nums[1] * nums[-1]
        b = nums[0] * nums[-2] * nums[-1]
        return max(a,b)