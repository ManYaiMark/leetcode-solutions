class Solution:
    '''
    โจทย์:
    กำหนดอาร์เรย์ nums มาให้ สามารถเพิ่มค่าของสมาชิกตัวใดก็ได้ครั้งละ 1 โดยห้ามลดค่า
    จงหาจำนวนครั้งขั้นต่ำที่ต้องเพิ่ม เพื่อทำให้สมาชิกทุกตัวในอาร์เรย์มีค่าเท่ากัน

    ไอเดีย ทำให้ทุกตัวเท่ากันกับตัวเลขที่มากสุด เลยใช้ sort และหาก len = 1  return 0

    ทำเสร็จไปดูของอีกคนมา วิธีคือ
    ทำให้ทุกตัวเท่ากับตัวที่มากที่สุดเหมือนกัน แต่จะใช้ max * len เพื่อหาว่าหากเป็นเลขสูงสุดทุกตัวจะได้ค่าเท่าไหร่ แล้วจึ่งลบกับ sum ค่าปัจจุบัน
    แปลงเป็นโค้ด max(nums) * len(nums) - sum(nums) 
    '''
    def minMoves(self, nums: List[int]) -> int:
        if len(nums) == 1 :
            return 0
        nums.sort()
        total = 0
        for i in range(len(nums)-1):
            total += nums[-1] - nums[i]
        return total
