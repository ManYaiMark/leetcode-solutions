class Solution:
    """
    โจทย์: กำหนด String ตัวเลข s และจำนวนเต็ม k ถ้าความยาวของ s มากกว่า k 
    ให้แบ่ง s จากซ้ายไปขวาเป็นกลุ่มละ k ตัว แล้วหาผลรวมของตัวเลขในแต่ละกลุ่มและนำผลรวมมาต่อกันเป็น String ใหม่ 
    ทำขั้นตอนนี้ซ้ำจนกระทั่งความยาวของ s น้อยกว่าหรือเท่ากับ k แล้วคืนค่า s

    วิธีคิด
    ใช้ while ในการเช็คหากยังเข้าเงื่อนไข ก้ให้ทำการทำซ้ำ
    ใช้ while เล็กในการทำการแบ่งกลุ่มและทำการ sum
    """
    def digitSum(self, s: str, k: int) -> str:
        while len(s) > k :
            n = ''
            while len(s) > k :
                m = s[0:k]
                n = n + str(sum([int(i) for i in m]))
                s = s[k:]  
            # n + sum(s) ตัวนี้สำคัญ เพราะ s ที่เหลือเศษจะไม่ถูกคิดรวม
            s = n + str(sum([int(i) for i in s]))
        return s